from statement_extractor.checks.printed import total_check
from statement_extractor.checks.subtotals import subtotals


def lines(*pairs):
    return [(label, 0, value) for label, value in pairs]


def test_a_total_proven_as_a_difference_counts():
    # JPM 2003: total net revenue is revenue before the provision less the provision.
    printed = lines(("Total noninterest revenue", 4700), ("Interest income", 5696), ("Interest expense", 2648),
                    ("Net interest income", 3048), ("Revenue before provision for credit losses", 7748),
                    ("Provision for credit losses", 223), ("Total net revenue", 7525))
    assert total_check(printed).result == "pass"


def test_a_total_first_under_its_heading_is_not_tested():
    # TSMC 2005: a supplemental block's "Total acquisitions" after the statement's closing balance.
    printed = lines(("Cash and cash equivalents, end of year", 96483.7)) + [("Cash paid for acquisition", 0, None)] + \
        lines(("Total acquisitions", 56166.2), ("Increase in payables", -1000.0))
    assert total_check(printed).result == "none"


def test_figures_in_printed_tenths_need_an_exact_sum():
    # TSMC 2015, in tenths of a million: 325 - 313 is not 0.
    printed = lines(("Long-term bank loans", 325), ("Deferred income tax liabilities", 313), ("Obligations under finance leases", 0))
    assert subtotals(printed) == {}


def test_a_cash_flow_section_is_named_by_its_first_section_word():
    from statement_extractor.domain.printed_labels import SECTION_KINDS
    assert SECTION_KINDS.search("Net cash used in investing activities from operations").group(2).lower() == "invest"
    assert SECTION_KINDS.search("Cash generated by operations").group(2).lower() == "operat"
    assert SECTION_KINDS.search("Cash used for investment activities").group(2).lower() == "invest"


def test_a_less_line_is_taken_away_in_brackets_or_not():
    # Costco 2009: "Less accumulated depreciation and amortization (4,302)".
    printed = lines(("Total current assets", 10087), ("Land", 3241), ("Buildings", 8014), ("Equipment", 3238),
                    ("Construction in progress", 307), ("Less accumulated depreciation and amortization", -4302),
                    ("Net property and equipment", 10498), ("Other assets", 719), ("Total assets", 21304))
    assert total_check(printed).result == "pass"


def test_a_line_named_as_the_other_line_above_it_or_as_its_heading_totals_its_block():
    # PepsiCo 2009: goodwill and other nonamortizable intangibles, then their total.
    pepsi = lines(("Total current assets", 10859), ("Net property, plant and equipment", 11306), ("Goodwill", 4988),
                  ("Other nonamortizable intangible assets", 1071), ("Nonamortizable intangible assets", 6059),
                  ("Other assets", 2293), ("Total assets", 30517))
    assert total_check(pepsi).result == "pass"
    # Kroger 2009: a heading, its lines and a line repeating the heading.
    kroger = lines(("Total current liabilities", 8170)) + [("Long-term debt including capital leases", 0, None)] + \
        lines(("Face-value long-term debt", 6932), ("Adjustment for interest rate hedges", 40),
              ("Long-term debt including capital leases", 6972), ("Other long-term liabilities", 1233),
              ("Total liabilities", 16375))
    assert total_check(kroger).result == "pass"


def test_lines_between_the_change_in_cash_and_its_opening_balance_adjust_it():
    from statement_extractor.checks.printed import cash_check
    # Kroger 2008: cash from a newly consolidated variable interest entity.
    printed = lines(("Net cash provided by operating activities", 900), ("Net cash used by investing activities", -500),
                    ("Net cash used by financing activities", -400), ("Net increase in cash", 0),
                    ("Cash from consolidated variable interest entity", 65),
                    ("Cash and temporary cash investments beginning of year", 242),
                    ("Cash and temporary cash investments end of quarter", 307))
    assert cash_check(printed).result == "pass"
